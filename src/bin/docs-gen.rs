    #[test]
    fn example_config_round_trips_to_defaults_when_uncommented() {
        let descriptions = real_descriptions();
        let toml_content = render_example_config_toml(&descriptions.descriptions);

        let mut uncommented = String::new();
        for line in toml_content.lines() {
            if let Some(rest) = line.strip_prefix("# ") {
                if let Some((key, _)) = rest.split_once(" = ") {
                    if !key.is_empty() && key.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
                    {
                        uncommented.push_str(rest);
                        uncommented.push('\n');
                        continue;
                    }
                }
                // Linea de prosa (descripcion o cabecera del archivo): se omite.
                continue;
            }
            uncommented.push_str(line);
            uncommented.push('\n');
        }

        let parsed: baud::config::Config =
            toml::from_str(&uncommented).expect("el config descomentado debe parsear");
        let expected = baud::config::Config::default_without_theme_import();
        assert_eq!(parsed.theme, expected.theme);
        assert_eq!(parsed.font.family, expected.font.family);
        assert_eq!(parsed.font.size, expected.font.size);
        assert_eq!(parsed.window.width, expected.window.width);
        assert_eq!(parsed.scrollback.lines, expected.scrollback.lines);
        assert_eq!(parsed.panes.max, expected.panes.max);
        assert_eq!(parsed.render.max_fps, expected.render.max_fps);
    }


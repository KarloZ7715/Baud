//! Generador de las paginas de referencia (config, keybindings, temas, CLI)
//! a partir de los binarios fuente. `cargo run --bin docs-gen` escribe las
//! paginas; `cargo run --bin docs-gen -- --check` las regenera en memoria y
//! compara contra lo commiteado, sin escribir nada.

use std::collections::{BTreeMap, BTreeSet};

const CONFIG_MD: &str = "docs/site/src/reference/config.md";
const KEYBINDINGS_MD: &str = "docs/site/src/reference/keybindings.md";
const THEMES_MD: &str = "docs/site/src/reference/themes.md";
const CLI_MD: &str = "docs/site/src/reference/cli.md";
const DESCRIPTIONS_TOML: &str = "docs/site/data/config-descriptions.toml";

const BANNER: &str = "<!--\nGenerated by `cargo run --bin docs-gen`. Do not edit by hand.\n-->\n\n";

/// Orden de despliegue de las secciones en `config.md`. Coincide con el
/// orden de los campos en `Config` salvo por `root`, que agrupa las claves
/// de nivel superior (`allow_osc52_read`, `bold_is_bright`, `keys`).
const SECTION_ORDER: &[&str] = &[
    "root",
    "theme",
    "font",
    "window",
    "selection",
    "copy_mode",
    "scrollback",
    "cursor",
    "process",
    "notifications",
    "panes",
    "status",
    "diagnostics",
    "debug",
    "render",
];

/// Tipo declarado para las claves `Option<T>` que valen `None` por defecto:
/// `serde_json` las serializa a `null`, perdiendo el tipo de `T`. Fuente
/// unica y pequeña para la excepcion, en el mismo espiritu que
/// `CONDITIONAL_BINDINGS` en `input::actions`.
const OPTIONAL_FIELD_TYPES: &[(&str, &str)] = &[
    ("cursor.color", "string"),
    ("status.bg_color", "string"),
    ("status.fg_color", "string"),
    ("diagnostics.log_level", "string"),
    ("diagnostics.reporting.dsn", "string"),
    ("diagnostics.reporting.enabled", "boolean"),
    ("process.program", "string"),
    ("process.working_directory", "string"),
    ("process.startup_command", "string"),
    ("process.distro", "string"),
    ("process.wsl_cwd", "string"),
];

#[derive(Debug, serde::Deserialize)]
struct DescriptionsFile {
    intro: BTreeMap<String, String>,
    descriptions: BTreeMap<String, String>,
}

#[derive(Debug, Clone)]
struct Row {
    path: String,
    ty: String,
    default: String,
    description: String,
}

fn main() {
    if let Err(code) = run() {
        std::process::exit(code);
    }
}

fn run() -> Result<(), i32> {
    let check = std::env::args().any(|a| a == "--check");

    let descriptions = load_descriptions(DESCRIPTIONS_TOML).map_err(|e| {
        eprintln!("docs-gen: {e}");
        1
    })?;

    let rows_by_section =
        build_rows(&descriptions.descriptions).map_err(|errs| report_errors(&errs))?;

    let pages: Vec<(&str, String)> = vec![
        (
            CONFIG_MD,
            render_config_md(&rows_by_section, &descriptions.intro),
        ),
        (KEYBINDINGS_MD, render_keybindings_md()),
        (THEMES_MD, render_themes_md()),
        (CLI_MD, render_cli_md()),
    ];

    if check {
        check_pages(&pages).map_err(|e| {
            eprintln!("docs-gen: {e}");
            1
        })?;
        println!("docs-gen: all generated pages are up to date.");
        Ok(())
    } else {
        for (path, content) in &pages {
            std::fs::write(path, content).map_err(|e| {
                eprintln!("docs-gen: could not write '{path}': {e}");
                1
            })?;
        }
        println!("docs-gen: wrote {} pages.", pages.len());
        Ok(())
    }
}

fn report_errors(errs: &[String]) -> i32 {
    for e in errs {
        eprintln!("docs-gen: {e}");
    }
    1
}

fn load_descriptions(path: &str) -> Result<DescriptionsFile, String> {
    let content = std::fs::read_to_string(path)
        .map_err(|e| format!("could not read descriptions file '{path}': {e}"))?;
    toml::from_str(&content).map_err(|e| format!("invalid descriptions file '{path}': {e}"))
}

/// Compara las paginas generadas contra lo commiteado. `Err` nombra la
/// primera que difiere (R8).
fn check_pages(pages: &[(&str, String)]) -> Result<(), String> {
    for (path, content) in pages {
        match std::fs::read_to_string(path) {
            Ok(existing) if &existing == content => {}
            Ok(_) => {
                return Err(format!(
                    "'{path}' is out of date. Run `cargo run --bin docs-gen`."
                ))
            }
            Err(e) => return Err(format!("could not read '{path}': {e}")),
        }
    }
    Ok(())
}

/// Recorre un `serde_json::Value` en profundidad y produce pares
/// (ruta con puntos, hoja). Una tabla vacia (`keys`, `process.env`) se trata
/// como su propia hoja en vez de continuar el recorrido, porque no tiene
/// claves fijas que enumerar.
fn walk_config(value: &serde_json::Value) -> Vec<(String, serde_json::Value)> {
    let mut out = Vec::new();
    walk_config_rec("", value, &mut out);
    out
}

fn walk_config_rec(
    prefix: &str,
    value: &serde_json::Value,
    out: &mut Vec<(String, serde_json::Value)>,
) {
    match value {
        serde_json::Value::Object(map) if !map.is_empty() => {
            for (k, v) in map {
                let path = if prefix.is_empty() {
                    k.clone()
                } else {
                    format!("{prefix}.{k}")
                };
                walk_config_rec(&path, v, out);
            }
        }
        _ => out.push((prefix.to_string(), value.clone())),
    }
}

fn section_key(path: &str) -> String {
    match path.find('.') {
        Some(idx) => path[..idx].to_string(),
        None => "root".to_string(),
    }
}

fn section_title(section: &str) -> &'static str {
    match section {
        "root" => "General",
        "theme" => "Theme",
        "font" => "Font",
        "window" => "Window",
        "selection" => "Selection",
        "copy_mode" => "Copy mode",
        "scrollback" => "Scrollback",
        "cursor" => "Cursor",
        "process" => "Process",
        "notifications" => "Notifications",
        "panes" => "Panes",
        "status" => "Status",
        "diagnostics" => "Diagnostics",
        "debug" => "Debug",
        "render" => "Render",
        _ => "Other",
    }
}

fn value_type(path: &str, value: &serde_json::Value) -> String {
    match value {
        serde_json::Value::String(_) => "string".to_string(),
        serde_json::Value::Bool(_) => "boolean".to_string(),
        serde_json::Value::Number(n) if n.is_f64() => "float".to_string(),
        serde_json::Value::Number(_) => "integer".to_string(),
        serde_json::Value::Array(_) => "array of strings".to_string(),
        serde_json::Value::Null => {
            let base = OPTIONAL_FIELD_TYPES
                .iter()
                .find(|(p, _)| *p == path)
                .map(|(_, t)| *t)
                .unwrap_or("string");
            format!("{base} (optional)")
        }
        serde_json::Value::Object(map) if map.is_empty() => "table".to_string(),
        serde_json::Value::Object(_) => {
            unreachable!("walk_config no deja objetos no vacios como hoja")
        }
    }
}

fn code_span(content: &str) -> String {
    if content.contains('`') {
        format!("`` {content} ``")
    } else {
        format!("`{content}`")
    }
}

fn value_default(value: &serde_json::Value) -> String {
    match value {
        serde_json::Value::String(s) => code_span(&format!("{s:?}")),
        serde_json::Value::Bool(b) => code_span(&b.to_string()),
        serde_json::Value::Number(n) => code_span(&n.to_string()),
        serde_json::Value::Array(items) => {
            let rendered = items
                .iter()
                .map(|item| match item {
                    serde_json::Value::String(s) => format!("{s:?}"),
                    other => other.to_string(),
                })
                .collect::<Vec<_>>()
                .join(", ");
            code_span(&format!("[{rendered}]"))
        }
        serde_json::Value::Null => "*(not set)*".to_string(),
        serde_json::Value::Object(map) if map.is_empty() => code_span("{}"),
        serde_json::Value::Object(_) => {
            unreachable!("walk_config no deja objetos no vacios como hoja")
        }
    }
}

/// Construye las filas de `config.md` agrupadas por seccion, validando
/// cobertura de descripciones en ambas direcciones (R7). `Err` lista cada
/// clave sin descripcion y cada entrada huerfana, nombrando la ruta.
fn build_rows(
    descriptions: &BTreeMap<String, String>,
) -> Result<BTreeMap<String, Vec<Row>>, Vec<String>> {
    let cfg = baud::config::Config::default();
    let value = serde_json::to_value(&cfg).expect("Config::default() serializa a JSON");
    let walked = walk_config(&value);

    let all_paths: BTreeSet<&str> = walked.iter().map(|(p, _)| p.as_str()).collect();
    let desc_paths: BTreeSet<&str> = descriptions.keys().map(|s| s.as_str()).collect();

    let missing: Vec<&&str> = all_paths.difference(&desc_paths).collect();
    let orphan: Vec<&&str> = desc_paths.difference(&all_paths).collect();
    if !missing.is_empty() || !orphan.is_empty() {
        let mut errs = Vec::new();
        for p in missing {
            errs.push(format!("missing description for config key '{p}'"));
        }
        for p in orphan {
            errs.push(format!("description entry '{p}' matches no config key"));
        }
        return Err(errs);
    }

    let mut rows_by_section: BTreeMap<String, Vec<Row>> = BTreeMap::new();
    for (path, leaf) in walked {
        let section = section_key(&path);
        let ty = value_type(&path, &leaf);
        let default = value_default(&leaf);
        let description = descriptions.get(&path).cloned().unwrap_or_default();
        rows_by_section.entry(section).or_default().push(Row {
            path,
            ty,
            default,
            description,
        });
    }
    for rows in rows_by_section.values_mut() {
        rows.sort_by(|a, b| a.path.cmp(&b.path));
    }
    Ok(rows_by_section)
}

fn render_config_md(
    rows_by_section: &BTreeMap<String, Vec<Row>>,
    intro: &BTreeMap<String, String>,
) -> String {
    let mut out = String::new();
    out.push_str(BANNER);
    out.push_str("# Configuration reference\n\n");
    out.push_str(
        "Every key `Config::default()` produces, grouped by TOML section and generated \
         from the compiled defaults plus hand-written prose. A key here always exists in \
         the current release; if it's missing, the build would have failed first.\n\n",
    );
    for section in SECTION_ORDER {
        let Some(rows) = rows_by_section.get(*section) else {
            continue;
        };
        out.push_str(&format!("## {}\n\n", section_title(section)));
        if let Some(text) = intro.get(*section) {
            out.push_str(text);
            out.push_str("\n\n");
        }
        for row in rows {
            out.push_str(&format!("### {}\n\n", row.path));
            out.push_str(&row.description);
            out.push_str("\n\n");
            out.push_str(&format!(
                "Type: {}. Default: {}.\n\n",
                code_span(&row.ty),
                row.default
            ));
        }
    }
    out
}

fn render_keybindings_md() -> String {
    let mut out = String::new();
    out.push_str(BANNER);
    out.push_str("# Keybindings reference\n\n");
    out.push_str(
        "Every default binding, as the exact chord and action strings `parse_binding` and \
         `parse_action` accept. Paste any row's Chord and Action into `[keys]` in your \
         config to reassign it.\n\n",
    );
    out.push_str("| Chord | Action | Platform |\n");
    out.push_str("| --- | --- | --- |\n");
    for (key, mods, action, platform) in baud::input::actions::all_default_bindings() {
        let chord = baud::input::actions::format_binding(key, mods);
        let platform_str = match platform {
            None => "All",
            Some(baud::input::actions::Platform::Windows) => "Windows",
        };
        out.push_str(&format!(
            "| `{}` | `{}` | {} |\n",
            chord,
            action.as_str(),
            platform_str
        ));
    }
    out.push('\n');
    out
}

fn swatch(hex: &str) -> String {
    format!(
        "<span style=\"display:inline-block;width:0.9em;height:0.9em;border-radius:2px;\
         vertical-align:middle;margin-right:0.35em;background:{hex};\
         border:1px solid rgba(127,127,127,0.4)\"></span>"
    )
}

fn render_themes_md() -> String {
    let mut out = String::new();
    out.push_str(BANNER);
    out.push_str("# Themes reference\n\n");
    out.push_str("Every embedded preset, generated from its TOML body. Pick one with `theme = \"name\"`.\n\n");
    for (name, theme) in baud::config::preset_entries() {
        out.push_str(&format!("## {name}\n\n"));
        out.push_str("| Color | Value |\n| --- | --- |\n");
        let mut entries: Vec<(&str, &str)> = vec![
            ("foreground", &theme.foreground),
            ("background", &theme.background),
            ("cursor", &theme.cursor),
            ("black", &theme.black),
            ("red", &theme.red),
            ("green", &theme.green),
            ("yellow", &theme.yellow),
            ("blue", &theme.blue),
            ("magenta", &theme.magenta),
            ("cyan", &theme.cyan),
            ("white", &theme.white),
            ("bright_black", &theme.bright_black),
            ("bright_red", &theme.bright_red),
            ("bright_green", &theme.bright_green),
            ("bright_yellow", &theme.bright_yellow),
            ("bright_blue", &theme.bright_blue),
            ("bright_magenta", &theme.bright_magenta),
            ("bright_cyan", &theme.bright_cyan),
            ("bright_white", &theme.bright_white),
        ];
        if let Some(bg) = &theme.selection_bg {
            entries.push(("selection_bg", bg));
        }
        if let Some(fg) = &theme.selection_fg {
            entries.push(("selection_fg", fg));
        }
        for (label, hex) in entries {
            out.push_str(&format!("| {label} | {} `{hex}` |\n", swatch(hex)));
        }
        out.push('\n');
    }
    out
}

fn render_cli_md() -> String {
    let mut out = String::new();
    out.push_str(BANNER);
    out.push_str("# CLI reference\n\n");
    out.push_str("Output of `baud help`, embedded verbatim.\n\n");
    out.push_str("```text\n");
    out.push_str(baud::cli::HELP_TEXT);
    if !baud::cli::HELP_TEXT.ends_with('\n') {
        out.push('\n');
    }
    out.push_str("```\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn real_descriptions() -> DescriptionsFile {
        load_descriptions(DESCRIPTIONS_TOML).expect("el archivo de descripciones real debe cargar")
    }

    #[test]
    fn build_rows_succeeds_with_the_real_descriptions_file() {
        let descriptions = real_descriptions();
        let rows_by_section = build_rows(&descriptions.descriptions).expect("cobertura completa");
        assert!(rows_by_section.contains_key("theme"));
        let total: usize = rows_by_section.values().map(|v| v.len()).sum();
        assert_eq!(total, 80, "cantidad de claves documentadas inesperada");
    }

    #[test]
    fn build_rows_fails_naming_a_missing_key() {
        let descriptions = real_descriptions();
        let mut broken = descriptions.descriptions.clone();
        broken.remove("theme.foreground");
        let errs = build_rows(&broken).expect_err("debe fallar con una clave faltante");
        assert!(errs
            .iter()
            .any(|e| e.contains("theme.foreground") && e.contains("missing")));
    }

    #[test]
    fn build_rows_fails_naming_an_orphan_entry() {
        let descriptions = real_descriptions();
        let mut broken = descriptions.descriptions.clone();
        broken.insert("theme.no_existe".to_string(), "huerfana".to_string());
        let errs = build_rows(&broken).expect_err("debe fallar con una entrada huerfana");
        assert!(errs
            .iter()
            .any(|e| e.contains("theme.no_existe") && e.contains("matches no config key")));
    }

    #[test]
    fn themes_page_has_one_entry_per_preset() {
        let rendered = render_themes_md();
        for name in baud::config::available_presets() {
            assert!(
                rendered.contains(&format!("## {name}\n")),
                "falta el preset '{name}' en la pagina de temas"
            );
        }
    }

    #[test]
    fn check_pages_ok_on_identical_content_and_fails_naming_a_diff() {
        let dir = tempfile::tempdir().expect("tempdir");
        let path = dir.path().join("page.md");
        std::fs::write(&path, "contenido\n").unwrap();
        let path_str = path.to_str().unwrap().to_string();

        let pages_ok: Vec<(&str, String)> = vec![(path_str.as_str(), "contenido\n".to_string())];
        assert!(check_pages(&pages_ok).is_ok());

        let pages_diff: Vec<(&str, String)> =
            vec![(path_str.as_str(), "otro contenido\n".to_string())];
        let err = check_pages(&pages_diff).expect_err("debe fallar tras mutar la pagina");
        assert!(err.contains(&path_str));
    }

    #[test]
    fn cli_page_embeds_help_text_verbatim() {
        let rendered = render_cli_md();
        assert!(rendered.contains(baud::cli::HELP_TEXT));
    }

    #[test]
    fn keybindings_page_covers_conditional_binding_platform_column() {
        let rendered = render_keybindings_md();
        assert!(rendered.contains("| Windows |"));
        assert!(rendered.contains("| All |"));
    }
}

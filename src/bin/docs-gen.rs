//! Generador de las paginas de referencia (config, keybindings, temas, CLI)
//! a partir de los binarios fuente. `cargo run --bin docs-gen` escribe las
//! paginas; `cargo run --bin docs-gen -- --check` las regenera en memoria y
//! compara contra lo commiteado, sin escribir nada.

use std::collections::{BTreeMap, BTreeSet};

const CONFIG_MD: &str = "docs/site/src/reference/config.md";
const KEYBINDINGS_MD: &str = "docs/site/src/reference/keybindings.md";
const THEMES_MD: &str = "docs/site/src/reference/themes.md";
const CLI_MD: &str = "docs/site/src/reference/cli.md";
const CHEATSHEET_MD: &str = "docs/site/src/reference/cheatsheet.md";
const EXAMPLE_CONFIG_MD: &str = "docs/site/src/reference/example-config.md";
const EXAMPLE_CONFIG_TOML: &str = "docs/site/src/reference/baud.toml";
const MAN_PAGE: &str = "packaging/man/baud.1";
const DESCRIPTIONS_TOML: &str = "docs/site/data/config-descriptions.toml";

const BANNER: &str = "<!--\nGenerated by `cargo run --bin docs-gen`. Do not edit by hand.\n-->\n\n";

/// Orden de despliegue de las secciones en `config.md`. Coincide con el
/// orden de los campos en `Config` salvo por `root`, que agrupa las claves
/// de nivel superior (`allow_osc52_read`, `bold_is_bright`, `keys`).
const SECTION_ORDER: &[&str] = &[
    "root",
    "theme",
    "font",
    "window",
    "selection",
    "copy_mode",
    "scrollback",
    "cursor",
    "process",
    "notifications",
    "panes",
    "status",
    "diagnostics",
    "debug",
    "render",
];

/// Tipo declarado para las claves `Option<T>` que valen `None` por defecto:
/// `serde_json` las serializa a `null`, perdiendo el tipo de `T`. Fuente
/// unica y pequeña para la excepcion, en el mismo espiritu que
/// `CONDITIONAL_BINDINGS` en `input::actions`.
const OPTIONAL_FIELD_TYPES: &[(&str, &str)] = &[
    ("cursor.color", "string"),
    ("status.bg_color", "string"),
    ("status.fg_color", "string"),
    ("diagnostics.log_level", "string"),
    ("diagnostics.reporting.dsn", "string"),
    ("diagnostics.reporting.enabled", "boolean"),
    ("process.program", "string"),
    ("process.working_directory", "string"),
    ("process.startup_command", "string"),
    ("process.distro", "string"),
    ("process.wsl_cwd", "string"),
    ("render.max_fps", "integer"),
];

#[derive(Debug, serde::Deserialize)]
struct DescriptionsFile {
    intro: BTreeMap<String, String>,
    descriptions: BTreeMap<String, String>,
}

#[derive(Debug, Clone)]
struct Row {
    path: String,
    ty: String,
    default: String,
    description: String,
}

fn main() {
    if let Err(code) = run() {
        std::process::exit(code);
    }
}

fn run() -> Result<(), i32> {
    let check = std::env::args().any(|a| a == "--check");

    let descriptions = load_descriptions(DESCRIPTIONS_TOML).map_err(|e| {
        eprintln!("docs-gen: {e}");
        1
    })?;

    let rows_by_section =
        build_rows(&descriptions.descriptions).map_err(|errs| report_errors(&errs))?;

    let example_toml = render_example_config_toml(&descriptions.descriptions);

    let pages: Vec<(&str, String)> = vec![
        (
            CONFIG_MD,
            render_config_md(&rows_by_section, &descriptions.intro),
        ),
        (KEYBINDINGS_MD, render_keybindings_md()),
        (THEMES_MD, render_themes_md()),
        (CLI_MD, render_cli_md()),
        (CHEATSHEET_MD, render_cheatsheet_md()),
        (EXAMPLE_CONFIG_MD, render_example_config_md(&example_toml)),
        (EXAMPLE_CONFIG_TOML, example_toml),
        (MAN_PAGE, render_man_page()),
    ];

    if check {
        check_pages(&pages).map_err(|e| {
            eprintln!("docs-gen: {e}");
            1
        })?;
        println!("docs-gen: all generated pages are up to date.");
        Ok(())
    } else {
        for (path, content) in &pages {
            std::fs::write(path, content).map_err(|e| {
                eprintln!("docs-gen: could not write '{path}': {e}");
                1
            })?;
        }
        println!("docs-gen: wrote {} pages.", pages.len());
        Ok(())
    }
}

fn report_errors(errs: &[String]) -> i32 {
    for e in errs {
        eprintln!("docs-gen: {e}");
    }
    1
}

fn load_descriptions(path: &str) -> Result<DescriptionsFile, String> {
    let content = std::fs::read_to_string(path)
        .map_err(|e| format!("could not read descriptions file '{path}': {e}"))?;
    toml::from_str(&content).map_err(|e| format!("invalid descriptions file '{path}': {e}"))
}

/// Compara las paginas generadas contra lo commiteado. `Err` nombra la
/// primera que difiere (R8).
fn check_pages(pages: &[(&str, String)]) -> Result<(), String> {
    for (path, content) in pages {
        match std::fs::read_to_string(path) {
            Ok(existing) if &existing == content => {}
            Ok(_) => {
                return Err(format!(
                    "'{path}' is out of date. Run `cargo run --bin docs-gen`."
                ))
            }
            Err(e) => return Err(format!("could not read '{path}': {e}")),
        }
    }
    Ok(())
}

/// Recorre un `serde_json::Value` en profundidad y produce pares
/// (ruta con puntos, hoja). Una tabla vacia (`keys`, `process.env`) se trata
/// como su propia hoja en vez de continuar el recorrido, porque no tiene
/// claves fijas que enumerar.
fn walk_config(value: &serde_json::Value) -> Vec<(String, serde_json::Value)> {
    let mut out = Vec::new();
    walk_config_rec("", value, &mut out);
    out
}

fn walk_config_rec(
    prefix: &str,
    value: &serde_json::Value,
    out: &mut Vec<(String, serde_json::Value)>,
) {
    match value {
        serde_json::Value::Object(map) if !map.is_empty() => {
            for (k, v) in map {
                let path = if prefix.is_empty() {
                    k.clone()
                } else {
                    format!("{prefix}.{k}")
                };
                walk_config_rec(&path, v, out);
            }
        }
        _ => out.push((prefix.to_string(), value.clone())),
    }
}

fn section_key(path: &str) -> String {
    match path.find('.') {
        Some(idx) => path[..idx].to_string(),
        None => "root".to_string(),
    }
}

/// Ancla estable derivada de una ruta con puntos (R14): un cambio de
/// redaccion del encabezado nunca rompe el enlace; un cambio de nombre de
/// clave lo rompe, a proposito.
fn anchor_slug(path: &str) -> String {
    path.replace('.', "-")
}

fn section_title(section: &str) -> &'static str {
    match section {
        "root" => "General",
        "theme" => "Theme",
        "font" => "Font",
        "window" => "Window",
        "selection" => "Selection",
        "copy_mode" => "Copy mode",
        "scrollback" => "Scrollback",
        "cursor" => "Cursor",
        "process" => "Process",
        "notifications" => "Notifications",
        "panes" => "Panes",
        "status" => "Status",
        "diagnostics" => "Diagnostics",
        "debug" => "Debug",
        "render" => "Render",
        _ => "Other",
    }
}

fn value_type(path: &str, value: &serde_json::Value) -> String {
    match value {
        serde_json::Value::String(_) => "string".to_string(),
        serde_json::Value::Bool(_) => "boolean".to_string(),
        serde_json::Value::Number(n) if n.is_f64() => "float".to_string(),
        serde_json::Value::Number(_) => "integer".to_string(),
        serde_json::Value::Array(_) => "array of strings".to_string(),
        serde_json::Value::Null => {
            let base = OPTIONAL_FIELD_TYPES
                .iter()
                .find(|(p, _)| *p == path)
                .map(|(_, t)| *t)
                .unwrap_or("string");
            format!("{base} (optional)")
        }
        serde_json::Value::Object(map) if map.is_empty() => "table".to_string(),
        serde_json::Value::Object(_) => {
            unreachable!("walk_config no deja objetos no vacios como hoja")
        }
    }
}

fn code_span(content: &str) -> String {
    if content.contains('`') {
        format!("`` {content} ``")
    } else {
        format!("`{content}`")
    }
}

/// Code span seguro dentro de una celda de tabla Markdown. mdBook parte las
/// filas de tabla en celdas por `|` antes de reconocer code spans, asi que
/// un pipe crudo (por ejemplo la chord `ctrl+shift+|`) rompe la fila aunque
/// vaya entre backticks; escaparlo a `\|` lo deja intacto (pulldown-cmark
/// desescapa el pipe de vuelta antes de renderizar el span).
fn table_cell_code(content: &str) -> String {
    code_span(&content.replace('|', "\\|"))
}

fn compact_json_number(n: &serde_json::Number) -> String {
    if n.as_i64().is_some() || n.as_u64().is_some() {
        return n.to_string();
    }
    let f = n.as_f64().expect("number");
    // serde_json expande f32 inexactos (0.6 -> 0.6000000238); 6 decimales
    // bastan para los defaults de config y recortan el ruido binario.
    let s = format!("{f:.6}");
    let trimmed = s.trim_end_matches('0').trim_end_matches('.');
    if trimmed.contains('.') {
        trimmed.to_string()
    } else {
        format!("{trimmed}.0")
    }
}

fn value_default(value: &serde_json::Value) -> String {
    match value {
        serde_json::Value::String(s) => code_span(&format!("{s:?}")),
        serde_json::Value::Bool(b) => code_span(&b.to_string()),
        serde_json::Value::Number(n) => code_span(&compact_json_number(n)),
        serde_json::Value::Array(items) => {
            let rendered = items
                .iter()
                .map(|item| match item {
                    serde_json::Value::String(s) => format!("{s:?}"),
                    other => other.to_string(),
                })
                .collect::<Vec<_>>()
                .join(", ");
            code_span(&format!("[{rendered}]"))
        }
        serde_json::Value::Null => "*(not set)*".to_string(),
        serde_json::Value::Object(map) if map.is_empty() => code_span("{}"),
        serde_json::Value::Object(_) => {
            unreachable!("walk_config no deja objetos no vacios como hoja")
        }
    }
}

/// Construye las filas de `config.md` agrupadas por seccion, validando
/// cobertura de descripciones en ambas direcciones (R7). `Err` lista cada
/// clave sin descripcion y cada entrada huerfana, nombrando la ruta.
fn build_rows(
    descriptions: &BTreeMap<String, String>,
) -> Result<BTreeMap<String, Vec<Row>>, Vec<String>> {
    let cfg = baud::config::Config::default_without_theme_import();
    let value = serde_json::to_value(&cfg).expect("Config::default() serializa a JSON");
    let walked = walk_config(&value);

    let all_paths: BTreeSet<&str> = walked.iter().map(|(p, _)| p.as_str()).collect();
    let desc_paths: BTreeSet<&str> = descriptions.keys().map(|s| s.as_str()).collect();

    let missing: Vec<&&str> = all_paths.difference(&desc_paths).collect();
    let orphan: Vec<&&str> = desc_paths.difference(&all_paths).collect();
    if !missing.is_empty() || !orphan.is_empty() {
        let mut errs = Vec::new();
        for p in missing {
            errs.push(format!("missing description for config key '{p}'"));
        }
        for p in orphan {
            errs.push(format!("description entry '{p}' matches no config key"));
        }
        return Err(errs);
    }

    let mut rows_by_section: BTreeMap<String, Vec<Row>> = BTreeMap::new();
    for (path, leaf) in walked {
        let section = section_key(&path);
        let ty = value_type(&path, &leaf);
        let default = value_default(&leaf);
        let description = descriptions.get(&path).cloned().unwrap_or_default();
        rows_by_section.entry(section).or_default().push(Row {
            path,
            ty,
            default,
            description,
        });
    }
    for rows in rows_by_section.values_mut() {
        rows.sort_by(|a, b| a.path.cmp(&b.path));
    }
    Ok(rows_by_section)
}

fn render_config_md(
    rows_by_section: &BTreeMap<String, Vec<Row>>,
    intro: &BTreeMap<String, String>,
) -> String {
    let mut out = String::new();
    out.push_str(BANNER);
    out.push_str("# Configuration reference\n\n");
    out.push_str(
        "Every key `Config::default()` produces, grouped by TOML section and generated \
         from the compiled defaults plus hand-written prose. A key here always exists in \
         the current release; if it's missing, the build would have failed first.\n\n",
    );
    for section in SECTION_ORDER {
        let Some(rows) = rows_by_section.get(*section) else {
            continue;
        };
        out.push_str(&format!(
            "## {} {{#config-section-{section}}}\n\n",
            section_title(section)
        ));
        if let Some(text) = intro.get(*section) {
            out.push_str(text);
            out.push_str("\n\n");
        }
        for row in rows {
            out.push_str(&format!(
                "### {} {{#config-{}}}\n\n",
                row.path,
                anchor_slug(&row.path)
            ));
            out.push_str(&row.description);
            out.push_str("\n\n");
            out.push_str(&format!(
                "Type: {}. Default: {}.\n\n",
                code_span(&row.ty),
                row.default
            ));
        }
    }
    out
}

fn render_keybindings_md() -> String {
    let mut out = String::new();
    out.push_str(BANNER);
    out.push_str("# Keybindings reference\n\n");
    out.push_str(
        "Every default binding, as the exact chord and action strings `parse_binding` and \
         `parse_action` accept. Paste any row's Chord and Action into `[keys]` in your \
         config to reassign it.\n\n",
    );
    out.push_str("| Chord | Action | Platform |\n");
    out.push_str("| --- | --- | --- |\n");
    for (key, mods, action, platform) in baud::input::actions::all_default_bindings() {
        let chord = baud::input::actions::format_binding(key, mods);
        let platform_str = match platform {
            None => "All",
            Some(baud::input::actions::Platform::Windows) => "Windows",
        };
        out.push_str(&format!(
            "| {} | {} | {} |\n",
            table_cell_code(&chord),
            table_cell_code(&action.as_str()),
            platform_str
        ));
    }
    out.push('\n');
    out
}

fn swatch(hex: &str) -> String {
    format!(
        "<span style=\"display:inline-block;width:0.9em;height:0.9em;border-radius:2px;\
         vertical-align:middle;margin-right:0.35em;background:{hex};\
         border:1px solid rgba(127,127,127,0.4)\"></span>"
    )
}

fn render_themes_md() -> String {
    let mut out = String::new();
    out.push_str(BANNER);
    out.push_str("# Themes reference\n\n");
    out.push_str("Every embedded preset, generated from its TOML body. Pick one with `theme = \"name\"`.\n\n");
    for (name, theme) in baud::config::preset_entries() {
        out.push_str(&format!("## {name} {{#theme-{name}}}\n\n"));
        out.push_str("| Color | Value |\n| --- | --- |\n");
        let mut entries: Vec<(&str, &str)> = vec![
            ("foreground", &theme.foreground),
            ("background", &theme.background),
            ("cursor", &theme.cursor),
            ("black", &theme.black),
            ("red", &theme.red),
            ("green", &theme.green),
            ("yellow", &theme.yellow),
            ("blue", &theme.blue),
            ("magenta", &theme.magenta),
            ("cyan", &theme.cyan),
            ("white", &theme.white),
            ("bright_black", &theme.bright_black),
            ("bright_red", &theme.bright_red),
            ("bright_green", &theme.bright_green),
            ("bright_yellow", &theme.bright_yellow),
            ("bright_blue", &theme.bright_blue),
            ("bright_magenta", &theme.bright_magenta),
            ("bright_cyan", &theme.bright_cyan),
            ("bright_white", &theme.bright_white),
        ];
        if let Some(bg) = &theme.selection_bg {
            entries.push(("selection_bg", bg));
        }
        if let Some(fg) = &theme.selection_fg {
            entries.push(("selection_fg", fg));
        }
        for (label, hex) in entries {
            out.push_str(&format!("| {label} | {} `{hex}` |\n", swatch(hex)));
        }
        out.push('\n');
    }
    out
}

fn render_cli_md() -> String {
    let mut out = String::new();
    out.push_str(BANNER);
    out.push_str("# CLI reference\n\n");
    out.push_str("Output of `baud help`, embedded verbatim.\n\n");
    out.push_str("```text\n");
    out.push_str(baud::cli::HELP_TEXT);
    if !baud::cli::HELP_TEXT.ends_with('\n') {
        out.push('\n');
    }
    out.push_str("```\n");
    out
}

fn render_cheatsheet_md() -> String {
    let mut out = String::new();
    out.push_str(BANNER);
    out.push_str("# Cheatsheet\n\n");
    out.push_str(
        "The same default bindings as the keybindings reference, grouped by what they're \
         for instead of by chord, for learning rather than lookup. Printable on one page.\n\n",
    );
    let bindings = baud::input::actions::all_default_bindings();
    for family in baud::input::actions::ACTION_FAMILY_ORDER {
        let rows: Vec<_> = bindings
            .iter()
            .filter(|(_, _, action, _)| action.family() == *family)
            .collect();
        if rows.is_empty() {
            continue;
        }
        out.push_str(&format!(
            "## {} {{#cheatsheet-{}}}\n\n",
            family.label(),
            family.label().to_ascii_lowercase()
        ));
        out.push_str("| Chord | Action | Platform |\n");
        out.push_str("| --- | --- | --- |\n");
        for (key, mods, action, platform) in rows {
            let chord = baud::input::actions::format_binding(*key, *mods);
            let platform_str = match platform {
                None => "All",
                Some(baud::input::actions::Platform::Windows) => "Windows",
            };
            out.push_str(&format!(
                "| {} | {} | {} |\n",
                table_cell_code(&chord),
                table_cell_code(&action.as_str()),
                platform_str
            ));
        }
        out.push('\n');
    }
    out
}

/// Literal TOML valido para una hoja, o `None` cuando la hoja no tiene
/// representacion literal significativa (`Option::None` serializado a
/// `null`, o una tabla vacia como `keys`/`process.env`).
fn toml_literal(value: &serde_json::Value) -> Option<String> {
    match value {
        serde_json::Value::String(s) => Some(toml_edit::Value::from(s.as_str()).to_string()),
        serde_json::Value::Bool(b) => Some(toml_edit::Value::from(*b).to_string()),
        serde_json::Value::Number(n) if n.is_f64() => Some(compact_json_number(n)),
        serde_json::Value::Number(n) => {
            Some(toml_edit::Value::from(n.as_i64().expect("entero fuera de rango")).to_string())
        }
        serde_json::Value::Array(items) => {
            let mut arr = toml_edit::Array::new();
            for item in items {
                if let serde_json::Value::String(s) = item {
                    arr.push(s.as_str());
                }
            }
            Some(toml_edit::Value::from(arr).to_string())
        }
        serde_json::Value::Null => None,
        serde_json::Value::Object(_) => None,
    }
}

/// True si esta tabla, o alguna anidada, produce al menos una linea
/// `clave = valor` en el config anotado. Evita encabezados `[section]`
/// vacios cuando todos sus campos son opcionales sin valor por defecto.
fn table_has_content(value: &serde_json::Value) -> bool {
    let serde_json::Value::Object(map) = value else {
        return false;
    };
    map.values().any(|v| match v {
        serde_json::Value::Object(inner) if !inner.is_empty() => table_has_content(v),
        _ => toml_literal(v).is_some(),
    })
}

/// Escribe recursivamente la tabla `value` (bajo la ruta `prefix`) como TOML
/// comentado: primero las claves de esta tabla, luego las subtablas no
/// vacias con su propio encabezado `[prefix.sub]`.
fn render_toml_table(
    prefix: &str,
    value: &serde_json::Value,
    descriptions: &BTreeMap<String, String>,
    out: &mut String,
) {
    let serde_json::Value::Object(map) = value else {
        return;
    };
    let mut nested: Vec<(&String, &serde_json::Value)> = Vec::new();
    for (k, v) in map {
        let path = if prefix.is_empty() {
            k.clone()
        } else {
            format!("{prefix}.{k}")
        };
        match v {
            serde_json::Value::Object(inner) if !inner.is_empty() => {
                if table_has_content(v) {
                    nested.push((k, v));
                }
            }
            _ => {
                if let Some(literal) = toml_literal(v) {
                    if let Some(desc) = descriptions.get(&path) {
                        out.push_str(&format!("# {desc}\n"));
                    }
                    out.push_str(&format!("# {k} = {literal}\n"));
                }
            }
        }
    }
    out.push('\n');
    for (k, v) in nested {
        let path = if prefix.is_empty() {
            k.clone()
        } else {
            format!("{prefix}.{k}")
        };
        out.push_str(&format!("[{path}]\n"));
        render_toml_table(&path, v, descriptions, out);
    }
}

fn render_example_config_toml(descriptions: &BTreeMap<String, String>) -> String {
    let cfg = baud::config::Config::default_without_theme_import();
    let value = serde_json::to_value(&cfg).expect("Config::default() serializa a JSON");
    let mut out = String::new();
    out.push_str("# Every option at its default, commented out. Uncomment and edit any\n");
    out.push_str("# line to override it. Generated by `cargo run --bin docs-gen`; options\n");
    out.push_str("# with no default shown here are unset in Config::default() (there is no\n");
    out.push_str("# literal TOML value for \"unset\") — see the configuration reference for\n");
    out.push_str("# their behavior when set.\n\n");
    render_toml_table("", &value, descriptions, &mut out);
    out
}

fn render_example_config_md(toml_content: &str) -> String {
    let mut out = String::new();
    out.push_str(BANNER);
    out.push_str("# Example config\n\n");
    out.push_str(
        "A fully commented `config.toml`, generated from the same defaults as the \
         configuration reference. [Download it](baud.toml) and uncomment what you want \
         to change.\n\n",
    );
    out.push_str("```toml\n");
    out.push_str(toml_content);
    out.push_str("```\n");
    out
}

fn escape_roff(s: &str) -> String {
    s.replace('\\', "\\\\").replace('-', "\\-")
}

struct HelpEntry {
    name: String,
    desc: String,
}

/// Divide una linea de `HELP_TEXT` en (nombre, descripcion) en el primer
/// tramo de 2+ espacios tras el nombre, que es como `cli::HELP_TEXT` alinea
/// sus columnas.
fn split_name_desc(line: &str) -> Option<(String, String)> {
    let trimmed = line.trim_start();
    if trimmed.is_empty() {
        return None;
    }
    let bytes = trimmed.as_bytes();
    for i in 0..bytes.len().saturating_sub(1) {
        if bytes[i] == b' ' && bytes[i + 1] == b' ' {
            let name = trimmed[..i].trim().to_string();
            let desc = trimmed[i..].trim().to_string();
            if name.is_empty() || desc.is_empty() {
                return None;
            }
            return Some((name, desc));
        }
    }
    None
}

/// Extrae las entradas nombre/descripcion del bloque de `HELP_TEXT` que
/// empieza en `header` (por ejemplo `"Commands:"`) hasta la siguiente linea
/// en blanco.
fn parse_help_block(text: &str, header: &str) -> Vec<HelpEntry> {
    let Some(start) = text.find(header) else {
        return Vec::new();
    };
    let after = &text[start + header.len()..];
    let block = after.split("\n\n").next().unwrap_or("");
    block
        .lines()
        .filter_map(split_name_desc)
        .map(|(name, desc)| HelpEntry { name, desc })
        .collect()
}

/// Rutas simbolicas de config, en el mismo orden de prioridad que
/// `Config::load` y `config::persist::config_paths`. Escritas a mano en vez
/// de invocar `config_paths()`: esa funcion resuelve `dirs::config_dir()` a
/// una ruta absoluta real de la maquina que ejecuta el generador, lo que
/// rompe `--check` entre entornos (equipo local vs CI). La forma simbolica
/// es portable y estable.
const CONFIG_FILE_LOCATIONS: &[(&str, &str)] = &[
    (
        "$XDG_CONFIG_HOME/baud/config.toml",
        "or ~/.config/baud/config.toml on Linux; %APPDATA%\\baud\\config.toml on Windows.",
    ),
    (
        "./baud.toml",
        "Working-directory fallback, checked if the file above is not found.",
    ),
];

fn render_man_page() -> String {
    let version = env!("CARGO_PKG_VERSION");
    let description = env!("CARGO_PKG_DESCRIPTION");
    let repository = env!("CARGO_PKG_REPOSITORY");

    let mut out = String::new();
    out.push_str(&format!(
        ".TH BAUD 1 \"\" \"baud {version}\" \"User Commands\"\n"
    ));
    out.push_str(".SH NAME\n");
    out.push_str(&format!("baud \\- {}\n", escape_roff(description)));
    out.push_str(".SH SYNOPSIS\n");
    out.push_str(".B baud\n[\\fIOPTIONS\\fR] [\\fICOMMAND\\fR]\n");
    out.push_str(".SH DESCRIPTION\n");
    out.push_str(&format!("{}\n", escape_roff(description)));
    out.push_str(
        "With no arguments, baud launches the graphical terminal. The commands and \
         options below are resolved before the graphical backend starts, so they also \
         work in a broken graphical session.\n",
    );
    out.push_str(".SH OPTIONS\n");
    for header in ["Commands:", "Options:", "Aliases:"] {
        for entry in parse_help_block(baud::cli::HELP_TEXT, header) {
            out.push_str(".TP\n");
            out.push_str(&format!("\\fB{}\\fR\n", escape_roff(&entry.name)));
            out.push_str(&format!("{}\n", escape_roff(&entry.desc)));
        }
    }
    out.push_str(".SH FILES\n");
    for (path, note) in CONFIG_FILE_LOCATIONS {
        out.push_str(".TP\n");
        out.push_str(&format!(".I {}\n", escape_roff(path)));
        out.push_str(&format!("{}\n", escape_roff(note)));
    }
    out.push_str(".SH SEE ALSO\n");
    out.push_str(&format!(
        "Full documentation: \\fI{}\\fR\n",
        escape_roff(repository)
    ));
    out
}

